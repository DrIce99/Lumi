test("policy context: off, not asked, locked, pause apps, do not disturb and away", () => {
  const close = { kind: "window" as const, action: "close" as const, app: "Discord" };
  const open = { kind: "open" as const, what: "app" as const, name: "Spotify", target: "spotify" };
  assert.equal(decide(open, ctx()).level, "free");
  assert.match(decide(open, ctx({ enabled: false })).reason, /off in the settings/);
  assert.match(decide(open, ctx({ requested: false })).reason, /only when the user asks/);
  assert.equal(decide(open, ctx({ locked: true })).level, "never");
  assert.equal(decide({ kind: "open", what: "app", name: "KeePassXC", target: "keepassxc.exe" }, ctx()).level, "never");
  assert.equal(decide({ kind: "window", action: "focus", app: "KeePass KeePass.exe" }, ctx()).level, "never");
  // Free actions asked explicitly still run in do not disturb; confirmations can't be asked there
  assert.equal(decide(open, ctx({ doNotDisturb: true })).level, "free");
  assert.equal(decide(close, ctx()).level, "confirm");
  assert.match(decide(close, ctx({ doNotDisturb: true })).reason, /can't answer now \(do not disturb\)/);
  assert.equal(decide(close, ctx({ away: true })).level, "never");
  // Without confirmations what would ask just runs; never stays never
  assert.equal(decide(close, ctx({ askFirst: false })).level, "free");
  assert.equal(decide(close, ctx({ askFirst: false, doNotDisturb: true })).level, "free");
  assert.equal(decide({ kind: "trash", path: "C:\\a.txt" }, ctx({ askFirst: false })).level, "free");
  assert.equal(decide({ kind: "delete", path: "C:\\a.txt" }, ctx({ askFirst: false })).level, "never");
  assert.equal(decide({ kind: "type_text", app: "Windows PowerShell" }, ctx({ askFirst: false })).level, "never");
  assert.match(decide(close, ctx({ askFirst: false, requested: false })).reason, /only when the user asks/);
});

