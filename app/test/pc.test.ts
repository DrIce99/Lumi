/** A fake desktop: windows appear when apps launch, input comes when the test says. */
function fakeHost(over: { settings?: Partial<Settings["pc"]>; answer?: boolean | null; files?: Record<string, "file" | "folder">; password?: boolean; modifier?: boolean; blocked?: boolean; answerFocusesLumi?: boolean } = {}) {
  const windows: WindowInfo[] = WINDOWS.map((w) => ({ ...w }));
  let foreground = "1";
  let tick = 1000;
  let lastInput = 900;
  const records: ActionRecord[] = [];
  const questions: string[] = [];
  const launched: string[] = [];
  const closed: string[] = [];
  const media: string[] = [];
  /** What reached each window: typed characters, and key presses as <vk>. */
  const typed: Record<string, string> = {};
  let line: string | null = "";
  const files: Record<string, "file" | "folder"> = { ...(over.files ?? {}) };
  const settings: Settings = { ...DEFAULT_SETTINGS, pc: { enabled: true, trustedApps: [], askFirst: true, ...over.settings }, perception: { ...DEFAULT_SETTINGS.perception, pauseInApps: ["KeePass"] } };
  const host: PcHost = {
    settings: () => settings,
    state: () => ({ doNotDisturb: false, away: false, locked: false }),
    index: { entries: () => ENTRIES, browserProgId: () => "ChromeHTML", refresh: async () => undefined, age: () => 0 },
    folder: (name) => `C:\\Users\\me\\${name}`,
    win: {
      list: () => windows,
      foregroundId: () => foreground,
      focus: (w) => {
        foreground = w.id;
        return true;
      },
      show: (w, action) => {
        w.minimized = action === "minimize";
        w.maximized = action === "maximize";
      },
      state: (w) => (windows.includes(w) ? { minimized: w.minimized, maximized: w.maximized, foreground: foreground === w.id } : null),
      close: (w) => {
        closed.push(w.id);
        windows.splice(windows.indexOf(w), 1);
        return true;
      },
      media: (action) => {
        media.push(action);
        const spotify = windows.find((w) => w.process === "Spotify.exe");
        if (spotify && action === "play_pause") spotify.title = spotify.title === "Spotify Premium" ? "Daft Punk - One More Time" : "Spotify Premium";
        return true;
      },
      lastInput: () => lastInput,
      tick: () => tick,
      foreground: () => windows.find((w) => w.id === foreground) ?? null,
      send: (events) => {
        if (over.blocked) return 0;
        for (const e of events) {
          if (e.flags & 2) continue; // key up
          const text = e.flags & 4 ? String.fromCharCode(e.scan) : `<${e.vk}>`;
          typed[foreground] = (typed[foreground] ?? "") + text;
          if (e.flags & 4) line = (line ?? "") + text;
        }
        return events.length;
      },
      modifierHeld: () => over.modifier === true,
    },
    field: () => ({ isPassword: over.password === true, line, processId: 0 }),
    launch: {
      explorer: async (arg) => {
        launched.push(arg);
        if (/Discord/.test(arg)) foreground = "2";
        if (/Balatro/.test(arg)) {
          windows.unshift(win("9", "Balatro.exe", "Balatro"));
        }
      },
      path: async (path) => {
        launched.push(path);
        return "";
      },
      external: async (url) => {
        launched.push(url);
      },
    },
    files: {
      expand: (p) => p.replace("%USERPROFILE%", "C:\\Users\\me"),
      kind: async (p) => files[p] ?? null,
      trash: async (p) => {
        delete files[p];
      },
      search: async () => [
        { path: "C:\\Users\\me\\Documenti\\bolletta luglio.pdf", name: "bolletta luglio.pdf", folder: false, modified: "2026-10-12T08:00:00Z", recent: true },
        { path: "C:\\Users\\me\\Download\\bolletta giugno.pdf", name: "bolletta giugno.pdf", folder: false, modified: "2026-07-03T08:00:00Z" },
      ],
    },
    confirm: async (question) => {
      questions.push(question);
      if (over.answerFocusesLumi) foreground = "lumi";
      tick += 10;
      lastInput = tick; // the click on the bubble
      return over.answer === undefined ? true : over.answer;
    },
    record: (r) => records.push(r),
    sleep: async () => {
      tick += 300;
    },
  };
  return {
    host,
    records,
    questions,
    launched,
    closed,
    media,
    files,
    typed,
    userInput: () => {
      lastInput = tick + 5;
    },
  };
}

